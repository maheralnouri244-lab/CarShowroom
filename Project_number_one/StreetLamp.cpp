#include "StreetLamp.h"
#include <cmath>

StreetLamp::StreetLamp(float h, float r) : height(h), baseRadius(r) {
    quad = gluNewQuadric();
    gluQuadricNormals(quad, GLU_SMOOTH); // ?????? ??????? ??? ?????? ????????
}

StreetLamp::~StreetLamp() {
    gluDeleteQuadric(quad);
}

void StreetLamp::drawBase() const {
    // ????? ???????/?????? ?????
    glColor3f(0.15f, 0.15f, 0.18f); // ????? ???? ????

    glPushMatrix();
    glRotatef(-90, 1, 0, 0); // ????? ??????

    // ?????? ???????
    gluCylinder(quad, baseRadius * 1.5f, baseRadius * 1.2f, 1.0f, 16, 1);
    glTranslatef(0, 0, 1.0f);

    // ?????? ??????? (???? ??????)
    gluCylinder(quad, baseRadius * 1.2f, baseRadius, 1.5f, 16, 1);

    glPopMatrix();
}

void StreetLamp::drawPole() const {
    glColor3f(0.2f, 0.2f, 0.22f); // ??? ?????? ?????

    glPushMatrix();
    glTranslatef(0, 2.5f, 0); // ??? ???????
    glRotatef(-90, 1, 0, 0);

    // ???? ????? (??? ???? ???? ???????)
    gluCylinder(quad, baseRadius, baseRadius * 0.6f, height - 4.0f, 16, 16);

    glPopMatrix();
}

void StreetLamp::drawArm() const {
    glPushMatrix();
    glTranslatef(0, height - 1.5f, 0); // ??? ??? ??????

    // ???? ??????
    glColor3f(0.25f, 0.25f, 0.27f);
    glutSolidSphere(baseRadius * 0.9f, 12, 12);

    // ?????? ?????? (Curve)
    // ????? ?????? ?? ?????????? ??????? ???????
    int segments = 10;
    float armLen = 8.0f;
    float angleStep = 20.0f / segments; // ?????? ???? 20 ????

    for (int i = 0; i < segments; i++) {
        glRotatef(angleStep, 1, 0, 0); // ??????
        gluCylinder(quad, baseRadius * 0.6f, baseRadius * 0.5f, armLen / segments, 12, 1);
        glTranslatef(0, 0, armLen / segments);
    }

    glPopMatrix();
}

void StreetLamp::drawLampHead(bool isNight) const {
    glPushMatrix();
    // ???? ???? ????? (?????? ????? ??? ??? ?????? ?????? ????????)
    // ???? ????? ?????????? ???? ????? ????? ??????
    glTranslatef(0, height + 1.0f, 7.5f);
    glRotatef(20, 1, 0, 0); // ????? ????? ????? ????? ?????? ???????

    // 1. ??? ?????? (Housing) - Cobra Head style
    glColor3f(0.15f, 0.15f, 0.18f);
    glPushMatrix();
    glScalef(1.5f, 0.6f, 2.5f); // ??? ????? ?????
    glutSolidSphere(1.0f, 16, 16);
    glPopMatrix();

    // 2. ??????/?????? (Bulb)
    glTranslatef(0, -0.3f, 0.5f); // ???? ????? ??????

    if (isNight) {
        // ??? ??? ?????? ???? ?????? ????? ????
        glPushAttrib(GL_LIGHTING_BIT);
        GLfloat emission[] = { 1.0f, 1.0f, 0.8f, 1.0f }; // ???? ????
        glMaterialfv(GL_FRONT, GL_EMISSION, emission);
        glColor3f(1.0f, 1.0f, 0.9f);
    }
    else {
        glColor3f(0.8f, 0.8f, 0.8f); // ???? ????
    }

    glPushMatrix();
    glScalef(1.2f, 0.2f, 1.8f);
    glutSolidSphere(0.8f, 16, 16);
    glPopMatrix();

    if (isNight) {
        glPopAttrib(); // ??????? ??????? ???????

        // ??? ?????? ??????
        drawLightCone();
    }

    glPopMatrix();
}

void StreetLamp::drawLightCone() const {
    // ????? ???????? ??????
    glPushAttrib(GL_ENABLE_BIT | GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDepthMask(GL_FALSE); // ?? ???? ?? ????? ??? ?? ???? ?? ??? ??????
    glDisable(GL_LIGHTING); // ?????? ?? ????? ?????

    glPushMatrix();
    glTranslatef(0, -0.5f, 0); // ????? ?????? ?? ??????
    glRotatef(90, 1, 0, 0);    // ????? ?????? ??????

    // ??? ????? ???? (??????)
    // ????? ???? ???? ?? ?????? ?????? (alpha = 0.15)
    glColor4f(1.0f, 0.95f, 0.6f, 0.15f);
    glutSolidCone(12.0f, 25.0f, 20, 10); // ????? ????? ???? ??? ?????

    // ????? ????? ???? ?????? (Core Beam)
    glColor4f(1.0f, 1.0f, 1.0f, 0.2f);
    glutSolidCone(5.0f, 20.0f, 20, 10);

    glPopMatrix();

    glPopAttrib();
}

void StreetLamp::draw(bool isNight) const {
    glPushMatrix();

    // ??? ????????
    drawBase();
    drawPole();
    drawArm();
    drawLampHead(isNight);

    glPopMatrix();
}
